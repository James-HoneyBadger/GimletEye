#!/usr/bin/env node
/**
 * The window, photographed, so a layout change is visible rather than argued about.
 *
 * Each shot is deterministic on purpose: a fresh profile and data directory, a
 * fixed size, a forced theme, animations off, the caret hidden, and the scrollbar
 * suppressed. Values that legitimately change between runs (durations, clock
 * times) carry `data-volatile` and are hidden before the capture.
 *
 *   node apps/desktop/e2e/shots.mjs            write every shot to e2e/shots/
 *   node apps/desktop/e2e/shots.mjs --update   replace the committed baselines
 *   node apps/desktop/e2e/shots.mjs --check    compare against the baselines
 *
 * Baselines are only comparable between machines with the same fonts and GPU
 * stack, which is why they are generated by the same runner the e2e job uses
 * in (see e2e/baselines/README.md). `--check` is advisory on a developer machine.
 */

import { chmodSync, copyFileSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { inflateSync } from 'node:zlib';

const here = dirname(fileURLToPath(import.meta.url));
const app = join(here, '..');
const baselineDir = join(here, 'baselines');
const shotsDir = join(here, 'shots');

const update = process.argv.includes('--update');
const check = process.argv.includes('--check');

const { _electron: electron } = await import('playwright');

const THEMES = ['dark', 'light'];
const SIZES = [
  { width: 1180, height: 800 },
  { width: 940, height: 640 },
];

/** Minimal PNG reader: 8-bit RGB or RGBA, all five filter types. */
function decode(buffer) {
  if (buffer.readUInt32BE(0) !== 0x89504e47) throw new Error('not a PNG');
  let position = 8;
  let width = 0;
  let height = 0;
  let depth = 0;
  let colour = 0;
  const parts = [];
  while (position < buffer.length) {
    const length = buffer.readUInt32BE(position);
    const type = buffer.toString('ascii', position + 4, position + 8);
    const data = buffer.subarray(position + 8, position + 8 + length);
    position += 12 + length;
    if (type === 'IHDR') {
      width = data.readUInt32BE(0);
      height = data.readUInt32BE(4);
      depth = data[8];
      colour = data[9];
    } else if (type === 'IDAT') {
      parts.push(data);
    } else if (type === 'IEND') {
      break;
    }
  }
  if (depth !== 8 || (colour !== 2 && colour !== 6)) {
    throw new Error(`unsupported PNG: depth ${depth}, colour ${colour}`);
  }
  const channels = colour === 6 ? 4 : 3;
  const raw = inflateSync(Buffer.concat(parts));
  const stride = width * channels;
  const out = Buffer.alloc(stride * height);
  let previous = Buffer.alloc(stride);
  for (let y = 0, at = 0; y < height; y += 1) {
    const filter = raw[at];
    at += 1;
    const line = Buffer.from(raw.subarray(at, at + stride));
    at += stride;
    for (let i = 0; i < stride; i += 1) {
      const left = i >= channels ? line[i - channels] : 0;
      const up = previous[i];
      const upLeft = i >= channels ? previous[i - channels] : 0;
      let value = line[i];
      if (filter === 1) value += left;
      else if (filter === 2) value += up;
      else if (filter === 3) value += (left + up) >> 1;
      else if (filter === 4) {
        const estimate = left + up - upLeft;
        const a = Math.abs(estimate - left);
        const b = Math.abs(estimate - up);
        const c = Math.abs(estimate - upLeft);
        value += a <= b && a <= c ? left : b <= c ? up : upLeft;
      }
      line[i] = value & 0xff;
    }
    line.copy(out, y * stride);
    previous = line;
  }
  return { width, height, channels, data: out };
}

/** Ignore antialiasing: a pixel counts only when a channel moved more than 16. */
function compare(expected, actual) {
  if (expected.width !== actual.width || expected.height !== actual.height) {
    return { ok: false, reason: `${actual.width}×${actual.height} vs baseline ${expected.width}×${expected.height}` };
  }
  const pixels = expected.width * expected.height;
  let differing = 0;
  for (let i = 0; i < pixels; i += 1) {
    const a = i * expected.channels;
    const b = i * actual.channels;
    const delta = Math.max(
      Math.abs(expected.data[a] - actual.data[b]),
      Math.abs(expected.data[a + 1] - actual.data[b + 1]),
      Math.abs(expected.data[a + 2] - actual.data[b + 2]),
    );
    if (delta > 16) differing += 1;
  }
  const ratio = differing / pixels;
  return { ok: ratio <= 0.002, ratio, differing };
}

const DETERMINISTIC_CSS = `
  [data-volatile] { visibility: hidden !important; }
  *, *::before, *::after { animation: none !important; transition: none !important; }
  * { caret-color: transparent !important; }
  ::-webkit-scrollbar { width: 0 !important; height: 0 !important; }
`;

/** Build a fixture tree with known modes, so findings do not depend on the host. */
function makeFixture(home) {
  const directory = join(home, 'shots-data');
  mkdirSync(directory, { recursive: true });
  const openDir = join(directory, 'open-dir');
  mkdirSync(openDir);
  // `mode` at creation is filtered by the umask; chmod is the only way to be sure.
  chmodSync(openDir, 0o777);
  writeFileSync(join(directory, 'open.txt'), 'world readable and writable\n');
  chmodSync(join(directory, 'open.txt'), 0o666);
  writeFileSync(join(directory, 'private.txt'), 'owner only\n');
  chmodSync(join(directory, 'private.txt'), 0o600);
  // A real photo with real EXIF, so the byte map has something to draw.
  copyFileSync(
    join(here, '..', '..', '..', 'packages', 'engine', 'test', 'fixtures', 'photo-exif-gps.jpg'),
    join(directory, 'photo.jpg'),
  );
  return directory;
}

async function shoot(window, name, target) {
  await window.waitForTimeout(220);
  const png = await window.screenshot();
  const path = join(target, `${name}.png`);
  writeFileSync(path, png);
  return path;
}

const results = [];

function baselineFiles() {
  try {
    return readdirSync(baselineDir)
      .filter((name) => name.endsWith('.png'))
      .sort();
  } catch {
    return [];
  }
}

async function session(theme, size) {
  const home = mkdtempSync(join(tmpdir(), 'gimlet-shots-'));
  const fixture = makeFixture(home);
  const electronApp = await electron.launch({
    args: [app, '--ozone-platform=x11', `--user-data-dir=${join(home, 'electron')}`],
    env: { ...process.env, GIMLET_HOME: home, GIMLET_SIDECAR: join(home, 'no-engine') },
    timeout: 60_000,
  });
  const window = await electronApp.firstWindow();
  await window.waitForSelector('.sidebar', { timeout: 30_000 });
  await electronApp.evaluate(async ({ BrowserWindow }, bounds) => {
    BrowserWindow.getAllWindows()[0].setSize(bounds.width, bounds.height);
  }, size);
  await window.waitForTimeout(400);

  const current = await window.evaluate(() => document.documentElement.dataset.theme);
  if (current !== theme) await window.click('#toggle-theme');
  await window.addStyleTag({ content: DETERMINISTIC_CSS });

  const target = update ? baselineDir : shotsDir;
  mkdirSync(target, { recursive: true });
  const prefix = `${theme}-${size.width}x${size.height}`;
  const capture = (state) => shoot(window, `${prefix}-${state}`, target);

  try {
    await capture('empty');

    await window.click('[data-tool="crypto.sha256"]');
    await capture('compose');

    await window.click('#open-palette');
    await window.fill('#palette-input', 'sha');
    await capture('palette');
    await window.keyboard.press('Escape');

    await window.click('[data-tool="crypto.sha256"]');
    await window.fill('input[name="text"]', 'hello');
    await window.click('#run');
    await window.waitForSelector('.report-title h1', { timeout: 30_000 });
    await capture('report');

    await window.click('[data-edit-parameters]');
    await window.click('[data-tool="sysadmin.file-permissions"]');
    await window.fill('input[name="path"]', fixture);
    await window.click('#run');
    await window.waitForSelector('.finding', { timeout: 30_000 });
    await capture('findings');

    await window.click('[data-edit-parameters]');
    await window.click('[data-tool="privacy.metadata-scan"]');
    await window.fill('input[name="input"]', join(fixture, 'photo.jpg'));
    await window.click('#run');
    await window.waitForSelector('.byte-map', { timeout: 30_000 });
    await capture('metadata');

    await window.click('[data-edit-parameters]');
    await window.click('[data-tool="privacy.metadata-scan"]');
    await window.fill('input[name="input"]', join(fixture, 'missing.jpg'));
    await window.click('#run');
    await window.waitForSelector('.callout--error', { timeout: 30_000 });
    await capture('failure');

    await window.click('#show-history');
    await window.waitForSelector('.run', { timeout: 10_000 });
    await capture('history');
    await window.keyboard.press('Escape');

    await window.click('#open-settings');
    await window.waitForSelector('[data-sheet-diagnostics]', { timeout: 10_000 });
    await capture('diagnostics');
  } finally {
    await electronApp.close().catch(() => undefined);
    rmSync(home, { recursive: true, force: true });
  }
}

let failed = 0;

for (const theme of THEMES) {
  for (const size of SIZES) {
    process.stdout.write(`  ${theme} ${size.width}×${size.height}\n`);
    await session(theme, size);
  }
}

if (check) {
  for (const file of baselineFiles()) {
    const expected = decode(readFileSync(join(baselineDir, file)));
    const actualPath = join(shotsDir, file);
    let actual;
    try {
      actual = decode(readFileSync(actualPath));
    } catch {
      results.push([file, { ok: false, reason: 'not captured' }]);
      failed += 1;
      continue;
    }
    const verdict = compare(expected, actual);
    results.push([file, verdict]);
    if (!verdict.ok) failed += 1;
  }
  for (const [file, verdict] of results) {
    const detail = verdict.ok
      ? `ok (${(verdict.ratio * 100).toFixed(3)}% pixels differ)`
      : verdict.reason ?? `${(verdict.ratio * 100).toFixed(2)}% pixels differ (${verdict.differing})`;
    process.stdout.write(`  ${verdict.ok ? 'ok  ' : 'FAIL'} ${file} — ${detail}\n`);
  }
  if (results.length === 0) {
    console.error('no baselines to compare; run --update under the same runner as the e2e job');
    process.exit(1);
  }
  process.stdout.write(`\nshots: ${results.length - failed}/${results.length} match\n`);
  process.exit(failed === 0 ? 0 : 1);
}

process.stdout.write(`\nshots written to ${update ? baselineDir : shotsDir}\n`);
